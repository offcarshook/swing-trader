"""Futures P&L accounting (realized, unrealized, fees, other charges).

Futures exchange no notional on entry: cash changes only by realized P&L,
fees and charges (e.g. roll costs); open positions contribute variation
(unrealized) P&L marked at the latest price. Prices are in index points,
P&L in dollars via the contract multiplier.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class Position:
    qty: int = 0              # signed: >0 long, <0 short
    avg_price: float = 0.0

    @property
    def side(self) -> int:
        return (self.qty > 0) - (self.qty < 0)


@dataclass
class Fill:
    ts: object
    instrument: str
    side: int        # +1 buy, -1 sell
    qty: int         # positive
    price: float
    fee: float
    realized: float
    tag: str = ""


@dataclass
class Ledger:
    starting_equity: float
    multipliers: dict[str, float]
    cash: float = field(init=False)
    realized_pnl: float = 0.0
    fees_paid: float = 0.0
    other_charges: float = 0.0
    positions: dict[str, Position] = field(default_factory=dict)
    marks: dict[str, float] = field(default_factory=dict)
    fills: list[Fill] = field(default_factory=list)

    def __post_init__(self):
        self.cash = float(self.starting_equity)

    # ------------------------------------------------------------------ fills
    def fill(self, instrument: str, side: int, qty: int, price: float, fee: float, ts=None, tag: str = "") -> float:
        """Apply a fill; returns realized P&L ($) generated by this fill (before fees)."""
        if side not in (1, -1) or qty <= 0:
            raise ValueError("side must be +/-1 and qty > 0")
        if fee < 0:
            raise ValueError("fee must be >= 0")
        mult = self.multipliers[instrument]
        pos = self.positions.setdefault(instrument, Position())
        signed = side * qty
        realized = 0.0
        if pos.qty == 0 or pos.side == side:
            new_qty = pos.qty + signed
            pos.avg_price = (pos.avg_price * abs(pos.qty) + price * qty) / abs(new_qty)
            pos.qty = new_qty
        else:
            closing = min(qty, abs(pos.qty))
            realized = (price - pos.avg_price) * closing * pos.side * mult
            remaining = qty - closing
            pos.qty += side * closing
            if pos.qty == 0:
                pos.avg_price = 0.0
            if remaining > 0:  # flip
                pos.qty = side * remaining
                pos.avg_price = price
        self.realized_pnl += realized
        self.fees_paid += fee
        self.cash += realized - fee
        self.marks[instrument] = price
        self.fills.append(Fill(ts, instrument, side, qty, price, fee, realized, tag))
        return realized

    def charge(self, amount: float, reason: str = "") -> None:
        if amount < 0:
            raise ValueError("charges must be >= 0")
        self.other_charges += amount
        self.cash -= amount

    # ---------------------------------------------------------------- marking
    def mark(self, instrument: str, price: float) -> None:
        self.marks[instrument] = price

    def unrealized(self, instrument: str | None = None) -> float:
        names = [instrument] if instrument else list(self.positions)
        total = 0.0
        for n in names:
            pos = self.positions.get(n)
            if pos and pos.qty:
                total += (self.marks[n] - pos.avg_price) * pos.qty * self.multipliers[n]
        return total

    def equity(self) -> float:
        return self.cash + self.unrealized()

    def position(self, instrument: str) -> Position:
        return self.positions.get(instrument, Position())

    def check_invariants(self, tol: float = 1e-6) -> None:
        expected = self.starting_equity + self.realized_pnl - self.fees_paid - self.other_charges
        if abs(self.cash - expected) > tol:
            raise AssertionError(f"cash {self.cash} != {expected}")
